/**
 * Generation pipeline: request → provider (with retries) → parse → sanitise →
 * validate → save as DRAFT. Never approves or publishes.
 *
 * Drafts are never lost:
 *  - the request is recorded before the provider is called;
 *  - a provider failure only marks that request failed — existing drafts are untouched;
 *  - output that parses but fails validation is still saved as a draft (with its
 *    report) so an author can fix it; output that does not parse is kept as raw
 *    text on the request record.
 * @module engine/generation/pipeline
 */
import { validateLesson } from '../schema/lessonSchema.js';
import { draftReview } from '../review/workflow.js';
import { normalizeRequest } from './request.js';
import { buildPrompt, extractJson } from './prompt.js';

export class ProviderError extends Error {
  constructor(message, { retryable = false, code = 'provider-error' } = {}) {
    super(message);
    this.name = 'ProviderError';
    this.retryable = retryable;
    this.code = code;
  }
}

const slug = (s) =>
  String(s)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 50) || 'lesson';

/** Force engine-controlled fields on untrusted provider output. */
export function sanitizeGenerated(raw, { provider, model, fallbackId, takenIds }) {
  const lesson = { ...raw };
  delete lesson.review;
  let id = typeof lesson.id === 'string' && /^[a-z0-9][a-z0-9-]{1,59}$/.test(lesson.id) ? lesson.id : slug(fallbackId);
  while (takenIds.has(id)) id = `${id.slice(0, 54)}-${Math.random().toString(36).slice(2, 6)}`;
  lesson.id = id;
  lesson.provenance = {
    origin: 'ai-generated',
    provider,
    model,
    createdAt: new Date().toISOString(),
    note: 'Generated draft — requires human review of maths, Egyptian Arabic, sources and narration before approval.',
  };
  if (lesson.animation?.narration) lesson.animation.narration = { status: 'none', assets: [] };
  lesson.review = draftReview([], `generated by ${provider}/${model}`);
  return lesson;
}

/**
 * @param {{ provider: { name, model, available, generate({system,user}) => Promise<string> },
 *           store, input, example, maxAttempts?, sleep? }} deps
 */
export async function runGeneration({ provider, store, input, example, maxAttempts = 3, sleep = (ms) => new Promise((r) => setTimeout(r, ms)) }) {
  const { ok, errors, request } = normalizeRequest(input);
  if (!ok) return { status: 'rejected-request', errors };

  const record = await store.saveRequest({ request, provider: provider.name, status: 'pending', createdAt: new Date().toISOString(), results: [] });

  if (!provider.available) {
    await store.updateRequest(record.id, { status: 'unavailable', error: provider.unavailableReason });
    return { status: 'unavailable', requestId: record.id, message: provider.unavailableReason };
  }

  const results = [];
  for (const lessonName of request.lessonNames) {
    const prompt = buildPrompt(request, lessonName, example);
    let textOut = null;
    let lastError = null;
    for (let attempt = 1; attempt <= maxAttempts; attempt++) {
      try {
        textOut = await provider.generate(prompt);
        break;
      } catch (e) {
        lastError = e;
        if (!(e instanceof ProviderError && e.retryable) || attempt === maxAttempts) break;
        await sleep(500 * 2 ** (attempt - 1));
      }
    }
    if (textOut === null) {
      results.push({ lessonName, status: 'provider-failed', error: lastError?.message ?? 'unknown error' });
      continue;
    }
    let raw;
    try {
      raw = extractJson(textOut);
    } catch (e) {
      results.push({ lessonName, status: 'unparseable', error: e.message, rawText: textOut.slice(0, 200000) });
      continue;
    }
    const takenIds = new Set((await store.list()).map((l) => l.id));
    const lesson = sanitizeGenerated(raw, { provider: provider.name, model: provider.model, fallbackId: lessonName, takenIds });
    const report = validateLesson(lesson);
    await store.saveLesson(lesson);
    results.push({ lessonName, status: report.ok ? 'draft-valid' : 'draft-invalid', lessonId: lesson.id, errors: report.errors.length, warnings: report.warnings.length });
  }

  const failed = results.every((r) => r.status === 'provider-failed' || r.status === 'unparseable');
  await store.updateRequest(record.id, { status: failed ? 'failed' : 'completed', results });
  return { status: failed ? 'failed' : 'completed', requestId: record.id, results };
}
