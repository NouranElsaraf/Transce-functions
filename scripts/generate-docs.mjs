#!/usr/bin/env node
/**
 * Documentation generator.
 *
 * Produces two Markdown files that stay in sync with the code:
 *   - docs/MODULES.md : every source file with a top-of-file `@module` JSDoc block
 *   - docs/LEVELS.md  : every level's metadata (from src/levels/<level>/meta.js)
 *
 * Usage:
 *   node scripts/generate-docs.mjs          # write docs
 *   node scripts/generate-docs.mjs --check  # exit 1 if docs are stale (used in CI)
 */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const DOCS = path.join(ROOT, 'docs');
const CHECK = process.argv.includes('--check');
const HEADER = '<!-- AUTO-GENERATED by scripts/generate-docs.mjs. Do not edit by hand. -->\n\n';

/** Recursively list files under `dir` matching `exts`. */
async function walk(dir, exts) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full, exts)));
    else if (exts.includes(path.extname(entry.name))) out.push(full);
  }
  return out.sort();
}

/** Extract the first JSDoc block containing `@module` from a source string. */
export function parseModuleDoc(source) {
  const match = source.match(/\/\*\*([\s\S]*?)\*\//);
  if (!match || !match[1].includes('@module')) return null;
  const lines = match[1]
    .split('\n')
    .map((l) => l.replace(/^\s*\*\s?/, '').trimEnd());
  const name = (lines.find((l) => l.startsWith('@module')) || '').replace('@module', '').trim();
  const description = lines
    .filter((l) => !l.startsWith('@'))
    .join('\n')
    .trim();
  return { name, description };
}

async function buildModulesDoc() {
  const files = await walk(SRC, ['.js', '.jsx']);
  const groups = new Map();
  for (const file of files) {
    const doc = parseModuleDoc(await readFile(file, 'utf8'));
    if (!doc) continue;
    const rel = path.relative(ROOT, file).split(path.sep).join('/');
    const group = rel.split('/').slice(1, 2)[0] || 'root';
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push({ rel, ...doc });
  }
  let md = HEADER + '# Module Reference\n\n';
  md += 'Every documented source file, grouped by folder. Add a `/** ... @module Name */` block at the top of a file to have it appear here.\n\n';
  for (const [group, mods] of groups) {
    md += `## \`src/${group}\`\n\n`;
    for (const m of mods) {
      md += `### ${m.name || path.basename(m.rel)}\n\n\`${m.rel}\`\n\n${m.description}\n\n`;
    }
  }
  return md;
}

async function buildLevelsDoc() {
  const levelsDir = path.join(SRC, 'levels');
  let md = HEADER + '# Level Guide\n\n';
  if (!existsSync(levelsDir)) return md + '_No levels yet._\n';
  const metas = [];
  for (const entry of await readdir(levelsDir, { withFileTypes: true })) {
    const metaPath = path.join(levelsDir, entry.name, 'meta.js');
    if (!entry.isDirectory() || !existsSync(metaPath)) continue;
    const mod = await import(pathToFileURL(metaPath).href);
    metas.push(mod.default);
  }
  metas.sort((a, b) => a.order - b.order);
  if (!metas.length) return md + '_No levels yet._\n';

  md += '| # | Level | Topic | Steps | Est. time |\n|---|---|---|---|---|\n';
  for (const m of metas) {
    md += `| ${m.order} | ${m.title} | ${m.topic} | ${m.steps.length} | ~${m.minutes} min |\n`;
  }
  md += '\n';
  for (const m of metas) {
    md += `## ${m.order}. ${m.title}\n\n> ${m.tagline}\n\n`;
    md += `**Big idea:** ${m.bigIdea}\n\n**Steps**\n\n`;
    m.steps.forEach((s, i) => {
      md += `${i + 1}. **${s.title}** — ${s.goal}\n`;
    });
    md += '\n';
  }
  return md;
}

async function main() {
  const outputs = {
    'MODULES.md': await buildModulesDoc(),
    'LEVELS.md': await buildLevelsDoc(),
  };
  await mkdir(DOCS, { recursive: true });
  let stale = false;
  for (const [name, content] of Object.entries(outputs)) {
    const target = path.join(DOCS, name);
    const current = existsSync(target) ? await readFile(target, 'utf8') : '';
    if (current === content) continue;
    if (CHECK) {
      console.error(`✗ docs/${name} is out of date. Run \`npm run docs\`.`);
      stale = true;
    } else {
      await writeFile(target, content);
      console.log(`✓ wrote docs/${name}`);
    }
  }
  if (stale) process.exit(1);
  if (CHECK) console.log('✓ docs are up to date');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
